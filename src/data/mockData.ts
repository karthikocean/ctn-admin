// Helper function to generate random replies
const generateReplies = (count: number, authorNames: string[] = allAuthorNames): Reply[] => {
  const replies: Reply[] = [];
  const colors = ["bg-blue-500", "bg-green-500", "bg-purple-500", "bg-orange-500", "bg-red-500", "bg-yellow-600", "bg-pink-500", "bg-indigo-500", "bg-teal-500", "bg-cyan-500", "bg-lime-500", "bg-amber-500", "bg-emerald-500", "bg-rose-500", "bg-violet-500", "bg-fuchsia-500", "bg-sky-500", "bg-stone-500", "bg-zinc-500", "bg-neutral-500"];
  const sampleContents = [
    "Great post! Very informative.",
    "I completely agree with this.",
    "Thanks for sharing your experience!",
    "This is really helpful.",
    "We've been doing something similar and it works!",
    "Could you elaborate more on this?",
    "Interesting perspective!",
    "We should discuss this further.",
    "Have you considered alternative approaches?",
    "This aligns with what we've seen.",
    "Looking forward to more insights!",
    "Thanks for the valuable input.",
    "We're facing a similar challenge.",
    "This gives me a lot to think about.",
    "Excellent point!",
  ];

  for (let i = 0; i < count; i++) {
    const author = authorNames[Math.floor(Math.random() * authorNames.length)];
    const nameParts = author.split(" ");
    const initials = nameParts.map(n => n[0]).join("").toUpperCase().slice(0, 2);
    const handle = "@" + author.toLowerCase().replace(/\s/g, "");
    const hasNested = Math.random() > 0.6;
    // Filter out current author for nested replies
    const nestedAuthorPool = authorNames.filter(a => a !== author);
    const nestedReplies = hasNested && nestedAuthorPool.length > 0
      ? generateReplies(Math.floor(Math.random() * 3) + 1, nestedAuthorPool)
      : undefined;

    replies.push({
      id: `r${Date.now()}-${i}`,
      authorName: author,
      authorHandle: handle,
      avatarColor: colors[Math.floor(Math.random() * colors.length)],
      initials: initials,
      timestamp: `${Math.floor(Math.random() * 24) + 1}h ago`,
      content: sampleContents[Math.floor(Math.random() * sampleContents.length)],
      nestedReplies: nestedReplies,
    });
  }

  return replies;
};

// Helper to generate date strings
const generateDate = (daysAgo: number): string => {
  const date = new Date();
  date.setDate(date.getDate() - daysAgo);
  return date.toISOString().split('T')[0];
};

